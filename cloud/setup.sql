-- 爪记 PawLog · 云端共享动态（Supabase）
-- 在 Supabase 项目的 SQL Editor 里整段执行即可。
-- 设计要点：anon 只允许「读全部 + 插入新行」，不允许改删；照片走公开读的 storage bucket。

-- 1) 动态表
create table if not exists public.pawlog_posts (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  author      text        not null,
  avatar      text,
  pet         text,
  city        text,
  body        text        not null,
  images      text[]      not null default '{}',
  likes       int         not null default 0
);

create index if not exists pawlog_posts_created_at_idx
  on public.pawlog_posts (created_at desc);

alter table public.pawlog_posts enable row level security;

drop policy if exists "pawlog read all"   on public.pawlog_posts;
drop policy if exists "pawlog anon insert" on public.pawlog_posts;

create policy "pawlog read all" on public.pawlog_posts
  for select using (true);

create policy "pawlog anon insert" on public.pawlog_posts
  for insert to anon with check (
    char_length(body) between 1 and 2000
    and char_length(coalesce(author, '')) between 1 and 60
    and coalesce(array_length(images, 1), 0) <= 4
  );

-- 2) 照片 bucket（公开读）
insert into storage.buckets (id, name, public)
values ('pawlog', 'pawlog', true)
on conflict (id) do update set public = true;

drop policy if exists "pawlog objects read"   on storage.objects;
drop policy if exists "pawlog objects anon add" on storage.objects;

create policy "pawlog objects read" on storage.objects
  for select using (bucket_id = 'pawlog');

create policy "pawlog objects anon add" on storage.objects
  for insert to anon
  with check (
    bucket_id = 'pawlog'
    and lower(storage.extension(name)) in ('jpg', 'jpeg', 'png', 'webp')
  );

